package com.baynana.domain.money

/**
 * نوع الوحدة الصغرى المعتمد لكل تخزين وحساب مالي في «بيننا».
 *
 * **القرار:** لا كسور عشرية في أي مسار حسابي (`Double`/`Float` ممنوعة في المال).
 * كل مبلغ يُخزَّن ويُحسب بالوحدة الصغرى صحيحة، ويُحوَّل إلى ريال عند العرض وعند الإدخال فقط،
 * ويُرسل ويُستقبل في الـAPI **نصًّا** (JSON number يتحول إلى double في الطرفين).
 *
 * **لماذا 64-بت لا 32-بت (Int):** الحد الأقصى لـ`Int` هو 2,147,483,647 فلسًا = **21.4 مليون
 * ريال** للقيمة الواحدة. وهذا ضيق لشروة أو صلح كبير، وأخطر منه أن **المجاميع** تتجاوزه بسهولة:
 * 500 قيد بمتوسط 500 ألف ريال = 25 مليار فلس. الفشل هناك تجاوز صامت يفسد أرصدة الناس.
 * `Long` نوع صحيح أيضًا (لا كسور ولا أخطاء قسمة)، وحدوده 9.2 × 10^18 فلسًا، وحجمه في Room
 * وخارج الجهاز واحد لأن SQLite تخزّن INTEGER بـ64-بت أصلًا. تُغيَّر القيمة من هنا وحدها لو
 * قرر المالك خلاف ذلك.
 */
typealias MinorUnits = Long

/**
 * عملات «بيننا» الأربع. القرار المعتمد: لا تحويل تلقائي بينها ولا مقاصة، ورصيد كل عملة مستقل.
 *
 * [minorUnits] عدد الخانات في الوحدة الصغرى: **فلسان (100 فلس للريال) في العملات الثلاث
 * اليمنية والسعودية، وسنتان للدولار**. الوحدة الصغرى لليمني هي الفلس كما قرر المالك، حتى لو
 * لم يعد الفلس متداولًا ورقًا؛ التخزين الدقيق يمنع تراكم الكسور في القسمة، والعرض يحذف
 * الكسر الصفري فلا يرى المستخدم إلا ريالات صحيحة إن لم يكن هناك كسر فعلي.
 */
enum class Currency(
    val code: String,
    val arabicName: String,
    val symbol: String,
    val minorUnits: Int
) {
    YER_OLD("YER_OLD", "ريال يمني قديم", "ر.ي قديم", 2),
    YER_NEW("YER_NEW", "ريال يمني جديد", "ر.ي", 2),
    SAR("SAR", "ريال سعودي", "ر.س", 2),
    USD("USD", "دولار أمريكي", "$", 2);

    /** عدد الوحدات الصغرى في وحدة واحدة: 100 في كل العملات الحالية. */
    val minorPerUnit: MinorUnits = if (minorUnits == 0) 1L else pow10(minorUnits)

    companion object {
        fun fromCode(code: String): Currency? = entries.firstOrNull { it.code == code }
    }
}

/**
 * لا تُوضع هذه الدالة داخل `companion object`: أسماء التعداد تُهيَّأ قبل رفيقها، فاستدعاؤها
 * من هناك يفشل بخطأ تهيئة وقت الترجمة. دالة على مستوى الملف آمنة.
 */
private fun pow10(exponent: Int): MinorUnits {
    var result = 1L
    repeat(exponent) { result *= 10L }
    return result
}

/** خطأ حسابي في المال. الرسالة عربية لأنها تُعرض للمستخدم في مسار الإدخال. */
class MoneyException(message: String) : IllegalArgumentException(message)
